-- RentGuard BUSFIN 4215 anonymous experiment tracking
-- Stores only aggregate-behavior event types and server timestamps.
-- No names, emails, addresses, payment data, lease data, photos, IP fields, or user identifiers are stored in this table.

create table if not exists public.experiment_events (
  id bigint generated by default as identity primary key,
  event_type text not null check (event_type in ('eligible_view', 'cta_click')),
  created_at timestamptz not null default now()
);

alter table public.experiment_events enable row level security;

drop policy if exists "anonymous can insert experiment events" on public.experiment_events;
create policy "anonymous can insert experiment events"
on public.experiment_events
for insert
to anon
with check (event_type in ('eligible_view', 'cta_click'));

grant insert on table public.experiment_events to anon;

-- Intentionally no SELECT policy for anonymous visitors.
